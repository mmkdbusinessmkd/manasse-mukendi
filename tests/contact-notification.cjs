const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('typescript');
require.extensions['.ts'] = (m, f) => m._compile(ts.transpileModule(fs.readFileSync(f, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText, f);
const validation = require('../lib/contact-request.ts');
const context = { exports: {}, process: { env: { ADMIN_EMAIL: 'owner@example.com' } }, fetch, AbortSignal, setTimeout, require: name => name === 'server-only' ? {} : name === './contact-request' ? validation : require(name) };
vm.runInNewContext(ts.transpileModule(fs.readFileSync('lib/contact-notification.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText, context);
const data = { name: 'Entreprise exemple', email: 'test@example.com', phone: '+243838000000', service: 'Stratégie digitale', message: 'Projet fictif.' };
const { notifyRequestOwner } = context.exports;
const response = (status, answer) => new Response(JSON.stringify(answer), { status, headers: { 'Content-Type': 'application/json' } });
(async () => {
  let calls = 0;
  const send = async (url, options) => {
    calls++;
    assert.equal(url, 'https://formsubmit.co/ajax/contact@manasse-mukendi.com');
    const body = JSON.parse(options.body);
    assert.equal(body._cc, 'owner@example.com');
    assert.equal(body._url, 'https://www.manasse-mukendi.com/');
    assert.equal(body._replyto, data.email);
    assert.equal(body.espace_prive, 'https://www.manasse-mukendi.com/admin/demandes/test-reference');
    assert.equal(body['Votre projet'], data.message);
    return response(200, { success: 'true' });
  };
  assert.equal((await notifyRequestOwner('test-reference', data, { fetch: send })).accepted, true);
  assert.equal(calls, 1);
  calls = 0;
  const wait = async () => {};
  const retry = await notifyRequestOwner('id', data, { wait, fetch: async () => { calls++; if (calls < 3) return response(503, {}); return response(200, { success: true }); } });
  assert.equal(retry.accepted, true); assert.equal(calls, 3);
  calls = 0;
  const failed = await notifyRequestOwner('id', data, { wait, fetch: async () => { calls++; throw Error('offline'); } });
  assert.equal(failed.accepted, false); assert.equal(calls, 3);
  const rejected = await notifyRequestOwner('id', data, { fetch: async () => response(200, { success: false }) });
  assert.equal(rejected.accepted, false); assert.equal(rejected.attempts, 1);
  const inactive = await notifyRequestOwner('id', data, { fetch: async () => response(200, { success: false, message: 'Activate your form first' }) });
  assert.equal(inactive.reason, 'activation_required');
  delete context.process.env.ADMIN_EMAIL;
  const missing = await notifyRequestOwner('id', data, { fetch: async () => { throw Error('Must not send with missing recipient'); } });
  assert.equal(missing.reason, 'configuration'); assert.equal(missing.attempts, 0);
  console.log('PASS: both owner addresses, original activation URL, reply-to, private request link, provider acknowledgement, bounded retries and explicit rejection.');
})().catch(e => { console.error(e); process.exitCode = 1; });
